-- The model catalog: parameter counts, one row per catalog key
-- (`docs/storage.md` §3.5). Columns rather than a body: each row is edited on
-- its own.
CREATE TABLE model_params (
    key              text PRIMARY KEY,
    total_millions   integer NOT NULL CHECK (total_millions > 0),
    active_millions  integer NOT NULL
        CHECK (active_millions > 0 AND active_millions <= total_millions),
    -- Where the counts come from, for a reader.
    note             text,
    updated_at       timestamptz NOT NULL,
    -- NULL on a row this migration seeded.
    updated_by       text
);

