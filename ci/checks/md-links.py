#!/usr/bin/env python3
"""Reject a relative Markdown link to a file or heading that does not exist.

The docs link to each other by path and by heading anchor, and GitHub renders a
broken one as a dead link with no warning. Renaming a heading or moving a file
breaks every link to it, so each tracked `.md` file's relative links are checked:

- **The file.** Resolved from the linking file's directory (a leading `/` from
  the repository root), it must exist. A directory counts.
- **The anchor.** A `#anchor` into a Markdown file must be one of its headings,
  slugged as GitHub does (lowercase; drop what is not a letter, digit, space,
  `-` or `_`; spaces to `-`; a repeat gains `-1`, `-2`), or an explicit
  `<a id>` / `<a name>`. An anchor into any other file (`#L10`) is not checked.

Web links, `mailto:` and links inside fenced or inline code are skipped.
"""

import re
import subprocess
import sys
from functools import cache
from pathlib import Path

FENCE = re.compile(r"^\s*(```|~~~)")
INLINE_CODE = re.compile(r"`+[^`]*`+")
INLINE_LINK = re.compile(r"\]\(([^)\s]*)(?:\s+\"[^\"]*\")?\)")
REFERENCE = re.compile(r"^\s*\[[^\]]+\]:\s*(\S+)")
HEADING = re.compile(r"^\s{0,3}#{1,6}\s+(.*?)\s*#*\s*$")
HTML_ANCHOR = re.compile(r"<a\s+(?:id|name)=\"([^\"]+)\"")
# Not this repository's prose: generated by `cargo about`, mostly license text.
GENERATED = {"THIRD-PARTY-LICENSES.md"}


def tracked_markdown() -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "*.md"], capture_output=True, text=True, check=True
    ).stdout.split()
    return sorted(p for p in out if p not in GENERATED)


def prose_lines(path: Path):
    """Each line outside fenced code, with its number."""
    fenced = False
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if FENCE.match(line):
            fenced = not fenced
            continue
        if not fenced:
            yield number, line


def slug(heading: str) -> str:
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", heading)  # a link keeps its label
    text = re.sub(r"[^\w\- ]", "", text.lower())
    return text.replace(" ", "-")


@cache
def anchors(path: Path) -> frozenset[str]:
    seen: dict[str, int] = {}
    out = set()
    for _, line in prose_lines(path):
        out.update(HTML_ANCHOR.findall(line))
        heading = HEADING.match(line)
        if not heading:
            continue
        base = slug(heading.group(1))
        count = seen.get(base, 0)
        seen[base] = count + 1
        out.add(base if count == 0 else f"{base}-{count}")
    return frozenset(out)


def targets(line: str) -> list[str]:
    line = INLINE_CODE.sub("", line)
    found = INLINE_LINK.findall(line)
    reference = REFERENCE.match(line)
    if reference:
        found.append(reference.group(1))
    return [t.strip("<>") for t in found]


def broken(root: Path, source: str) -> list[str]:
    path = root / source
    out = []
    for number, line in prose_lines(path):
        for target in targets(line):
            if not target or "://" in target or target.startswith("mailto:"):
                continue
            file, _, anchor = target.partition("#")
            if not file:
                linked = path
            elif file.startswith("/"):
                linked = root / file.lstrip("/")
            else:
                linked = path.parent / file
            where = f"{source}:{number}: {target}"
            if not linked.exists():
                out.append(f"{where} (no such file)")
            elif anchor and linked.suffix == ".md" and anchor not in anchors(linked.resolve()):
                out.append(f"{where} (no such heading)")
    return out


def main() -> int:
    root = Path(subprocess.run(
        ["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True, check=True
    ).stdout.strip())
    found = [b for source in tracked_markdown() for b in broken(root, source)]
    if found:
        print("error: Markdown links to a file or heading that does not exist:")
        for b in found:
            print(f"  {b}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
